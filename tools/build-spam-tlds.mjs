// ── tools/build-spam-tlds.mjs ────────────────────────────────────────────────
// Converts HaGeZi's "The World's Most Abused TLDs" (uBlock syntax) into
// data/spam-tlds.js — the single source of truth for the TLD blocklist.
//
// Usage:  node build-spam-tlds.mjs [--extension ../3P-Matrix] [--check] [path/to/spam-tlds-ublock.txt]
//         input defaults to spam-tlds-ublock.txt next to this script; --extension defaults to the
//         sibling folder ../3P-Matrix (the release layout: 3P-Matrix-tools next to 3P-Matrix).
//         --check: write nothing; exit 1 when the extension's data/spam-tlds.js differs from what this
//         input generates (suite step: the shipped list matches its recorded source — C13a).
//         4.2.3: the output path was "../data/spam-tlds.js", which only worked with tools/ INSIDE the
//         extension folder; since 0.2.0 the folders are siblings, so it pointed outside the extension.
//
// Input line shape:  ||<tld>^$doc[,domain=~a.tld|~b.tld]
//   <tld>               → SPAM_TLDS
//   ~a.tld (exceptions) → SPAM_TLD_EXCEPTIONS (legitimate sites on that TLD)
// Lines starting with "!" or "[" are comments/headers and are skipped.
// 4.4.0: every other line goes through dnr-filter.mjs — rules DNR cannot express (cosmetic, scriptlets,
// $redirect, …) are DROPPED on purpose, reported and counted in the generated header; a rule DNR COULD
// express but in a shape this builder does not understand makes the build FAIL (never lost silently).
// ─────────────────────────────────────────────────────────────────────────────

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { filterList } from "./dnr-filter.mjs";   // 4.4.0: explicit DNR verdict per list line
import { recordList } from "./list-modules.mjs";  // 4.6.0: records the rebuild in data-sources.json like every list tool (C44)

// ── Configuration (all switches in one place) ───────────────────────────────
const HERE           = dirname(fileURLToPath(import.meta.url));
const DEFAULT_INPUT  = join(HERE, "spam-tlds-ublock.txt");
const REGISTER_ID    = "abused-tlds";                  // data-sources.json lists.<id>
const TOOL_NAME      = "build-spam-tlds.mjs";
const DEFAULT_EXTENSION = join(HERE, "..", "3P-Matrix");     // sibling folder in the release layout
const OUTPUT_REL     = join("data", "spam-tlds.js");
const EXIT           = Object.freeze({ OK: 0, FAILED: 1, DID_NOT_RUN: 2 });
const LINE_RE        = /^\|\|([^\^]+)\^\$doc(?:,domain=(.+))?$/;   // ||tld^$doc[,domain=...]
const MIN_TLDS       = 100;   // guard: refuse to write a suspiciously small list (truncated download)
const MAX_LISTED     = 20;    // 4.4.0: not-understood rules printed in the report (the count is always shown)

function parse(text) {
  const tlds = new Set();
  const exceptions = new Set();
  let version = "";
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line.startsWith("! Version:")) version = line.slice("! Version:".length).trim();
  }
  const filtered = filterList(text, LINE_RE);                    // 4.4.0: explicit DNR verdict per line
  for (const line of filtered.kept) {
    const m = LINE_RE.exec(line);
    tlds.add(m[1].toLowerCase());
    if (m[2]) {
      for (const d of m[2].split("|")) {
        if (d.startsWith("~")) exceptions.add(d.slice(1).toLowerCase());
      }
    }
  }
  return { tlds: [...tlds].sort(), exceptions: [...exceptions].sort(), version,
           read: filtered.read, dropped: filtered.dropped, unhandled: filtered.unhandled };
}

// 4.4.0: what was dropped and why (grouped by reason), and the shapes the builder does not understand.
function report({ read, tlds, dropped, unhandled }) {
  console.log(`build-spam-tlds: ${read} rules read · ${read - dropped.length - unhandled.length} kept (${tlds.length} TLDs) · ` +
              `${dropped.length} dropped (not expressible as DNR) · ${unhandled.length} not understood`);
  const byReason = new Map();
  for (const d of dropped) byReason.set(d.reason, (byReason.get(d.reason) || 0) + 1);
  for (const [reason, n] of byReason) console.log(`  dropped ${n}× — ${reason}`);
  for (const u of unhandled.slice(0, MAX_LISTED)) console.log(`  NOT UNDERSTOOD — ${u.line}`);
}

function render({ tlds, exceptions, version, read, dropped }) {
  const list = (arr) => arr.map((s) => JSON.stringify(s)).join(",");
  return `// ── data/spam-tlds.js — GENERATED by tools/build-spam-tlds.mjs, do not edit ──
// Source: HaGeZi "The World's Most Abused TLDs" (uBlock syntax), version ${version || "unknown"}
// Rules read: ${read} · kept: ${read - dropped.length} · dropped as not expressible by declarativeNetRequest: ${dropped.length}
// https://github.com/hagezi/dns-blocklists — license: see that repository.
//
// SPAM_TLDS            — abused TLDs (no leading dot); 3P scripts/frames blocked from L2,
//                        first-party visit = heuristics signal
// SPAM_TLD_EXCEPTIONS  — legitimate sites on those TLDs (never warned, never blocked)
export const SPAM_TLDS = Object.freeze([${list(tlds)}]);
export const SPAM_TLD_EXCEPTIONS = Object.freeze([${list(exceptions)}]);
`;
}

function parseArgs(argv) {
  const out = { extension: DEFAULT_EXTENSION, check: false, input: DEFAULT_INPUT };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--extension") out.extension = argv[++i];
    else if (argv[i] === "--check") out.check = true;
    else out.input = argv[i];
  }
  return out;
}

const args = parseArgs(process.argv.slice(2));
if (!args.extension || !existsSync(join(args.extension, "manifest.json"))) {
  console.error(`build-spam-tlds: DID NOT RUN — not an extension folder: ${args.extension}`);
  process.exit(EXIT.DID_NOT_RUN);
}
if (!existsSync(args.input)) {
  console.error(`build-spam-tlds: DID NOT RUN — input not found: ${args.input}`);
  process.exit(EXIT.DID_NOT_RUN);
}
const outputPath = join(args.extension, OUTPUT_REL);
const parsed = parse(readFileSync(args.input, "utf8"));
report(parsed);
if (parsed.unhandled.length > 0) {
  console.error(`build-spam-tlds: FAIL — ${parsed.unhandled.length} rule(s) DNR could express but this builder does not ` +
                `understand; teach LINE_RE / parse() the shape (dropping them would lose list data silently).`);
  process.exit(EXIT.FAILED);
}
if (parsed.tlds.length < MIN_TLDS) {
  console.error(`Refusing to write: only ${parsed.tlds.length} TLDs parsed (expected ≥ ${MIN_TLDS}).`);
  process.exit(EXIT.FAILED);
}
const generated = render(parsed);
if (args.check) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error(`build-spam-tlds: FAIL — ${outputPath} differs from what ${args.input} generates (run without --check).`);
    process.exit(EXIT.FAILED);
  }
  console.log(`build-spam-tlds: PASS — ${OUTPUT_REL} matches its source (${parsed.tlds.length} TLDs, version ${parsed.version}).`);
  process.exit(EXIT.OK);
}
writeFileSync(outputPath, generated);
// 4.6.0: the register entry (version, count, source release) was updated by hand until now — a list tool that does
// not record its own rebuild is the C44 gap check-list-freshness.mjs exists for.
const recordedFor = recordList(REGISTER_ID, args.extension, { sourceRelease: parsed.version, entries: parsed.tlds.length, tool: TOOL_NAME });
console.log(`Wrote ${outputPath}: ${parsed.tlds.length} TLDs, ${parsed.exceptions.length} exceptions (version ${parsed.version}), recorded for ${recordedFor}.`);
