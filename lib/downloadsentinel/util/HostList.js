/**
 * 3P Matrix (4.5.4): this list ships as a precompiled JSON string in HostList.default.js, rebuilt by
 * tools/rebuild-host-list.mjs (registered in its data-sources.json; source: https://github.com/hagezi/dns-blocklists (wildcard/dyndns-onlydomains.txt, wildcard/hoster-onlydomains.txt); https://github.com/Kees1958/W3C_annual_most_used_survey_blocklist (Suspicious websites.txt)).
 * data/… paths below are DownloadSentinel's own (its repo's data/ folder), not 3P Matrix's data/.
 *
 * HostList.js
 *
 * Merged, deduplicated host-risk list (heuristics plan Step 1, v2.7.0):
 *   HaGeZi "DynDNS"           — dynamic-DNS providers abused for phishing
 *   HaGeZi "Badware Hoster"   — free/hosting platforms with repeat abuse
 *   Kees1958 "Suspicious websites" — free-hosting/script-hosting domains
 *     (lower score — see tools/update-lists.mjs's SOURCES.KEES_SUSPICIOUS
 *     comment for why this list's semantics differ from the other two)
 *
 * This is a RISK VALUE, not a block — a hit here alone should land in the
 * "moderate" classification range. It only becomes a decisive signal when
 * combined with other host-reputation signals (heuristics plan Step 3,
 * v2.9.0 — see ScoringEngineV2.js's evaluateHostReputation / Combination
 * Scoring.js). Consumed by BOTH the 3P-Matrix site-visit warning
 * (core/site-scorer.js, HostList.lookup()) and the download warning
 * (core/download-guard.js via BrowserProtection.js → ScoringEngineV2.js) —
 * not download-only.
 *
 * The Kees1958 entries here are NOT a duplicate of 3P Matrix's own
 * data/suspicious-hosting.js (protection 6): that file ingests the SAME
 * upstream list independently, as a separate snapshot, for a hard BLOCK
 * decision (site-visit only). This file's copy is a moderate risk score
 * for both site-visit and download warnings. Two deliberate snapshots of
 * one source for two different jobs — see that file's own header.
 *
 * Matches on the full hostname first, then the registered domain (last two
 * labels) — same lookup shape as SuspiciousDomains.lookup(), so subdomains of
 * a listed domain are caught even when only the registered domain is listed.
 *
 * The raw TABLE lives in data/HostList.json (regenerated by
 * `tools/update-lists.mjs`, which writes the JSON — see that script's own
 * header), and this module only holds the lookup LOGIC plus the
 * compiled-in default (generated from that JSON by
 * `tools/gen-data-defaults.mjs` — see HostList.default.js's own header),
 * which is the only data this module ever loads at runtime — v3.3.0 (3P
 * Matrix alignment item 18) removed the remote-refresh mechanism
 * (util/FilterDataLoader.js) that used to call setData() here with a
 * freshly-fetched copy. setData() remains for tests.
 */
import { HostListDefaultJson } from "./HostList.default.js";
import { lazyJson } from "./LazyJson.js";

export const HostList = (function () {

    // 3P Matrix 4.5.4 (perf P4): parsed on first lookup, not at service-worker start (util/LazyJson.js).
    const defaultData = lazyJson(HostListDefaultJson);
    let TABLE = null;       // null = use the default (parsed on first use); setData() replaces it
    function data() { return TABLE === null ? (TABLE = defaultData()) : TABLE; }

    /**
     * Look up a hostname in the merged list.
     *
     * Checks the full hostname first, then walks up each parent domain
     * (dropping one leftmost label at a time) until a match is found or only
     * a single label remains. This is a generalisation of
     * SuspiciousDomains.lookup()'s "full hostname, then last-two-labels"
     * pattern: most listed entries here ARE just a two-label registered
     * domain (that simpler check would suffice), but a handful of entries in
     * the merged list (e.g. multi-label dyndns providers like
     * "dyn.addr.tools") are themselves 3+ labels, so a plain
     * last-two-labels check would miss a subdomain of one of THOSE (e.g.
     * "www.dyn.addr.tools") — walking the full label chain closes that gap.
     *
     * @param {string} hostname
     * @returns {{ score: number, matchedDomain: string, source: string } | null}
     */
    function lookup(hostname) {
        if (!hostname) return null;
        const parts = hostname.toLowerCase().split(".");

        for (let i = 0; i < parts.length - 1; i++) {
            const candidate = parts.slice(i).join(".");
            const hit = data()[candidate];
            if (hit !== undefined) {
                return { score: hit.score, matchedDomain: candidate, source: hit.source };
            }
        }

        return null;
    }

    function setData(newTable) {
        TABLE = newTable;
    }

    function resetToDefault() {
        TABLE = null;           // released: the next lookup goes back to the default
    }

    return { lookup, setData, resetToDefault, get _ENTRY_COUNT() { return Object.keys(data()).length; } };
})();
